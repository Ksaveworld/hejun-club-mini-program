import {mkdir} from 'node:fs/promises';
import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium,expect,request} from '@playwright/test';
import {PDFDocument} from 'pdf-lib';
import {randomUUID} from 'node:crypto';
import {grantRuntime} from '../fixtures/grant-runtime.mjs';

test('built admin UI → real HTTPS grant → native API full PDF/post → revoke, preserving history and account isolation',{timeout:90000},async t=>{
  const f=await grantRuntime(t),browser=await chromium.launch({channel:'msedge',headless:true});t.after(()=>browser.close());
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1100}}),page=await context.newPage();
  page.setDefaultTimeout(15000);const errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  await context.route('**/*',route=>{if(new URL(route.request().url()).origin!==f.origin){external.push(route.request().url());return route.abort();}return route.continue();});
  const native=await request.newContext({ignoreHTTPSErrors:true,extraHTTPHeaders:{Authorization:'Bearer '+f.native.accessToken,'x-club-request':'1'}});
  const other=await request.newContext({ignoreHTTPSErrors:true,extraHTTPHeaders:{Authorization:'Bearer '+f.other.accessToken,'x-club-request':'1'}});
  t.after(async()=>{await native.dispose();await other.dispose();});
  const fullUrl=f.origin+'/api/articles/'+f.reportId+'/document';
  assert.equal((await native.get(fullUrl)).status(),404);
  assert.equal((await native.post(f.origin+'/api/posts',{data:{title:'Before',body:'SYNTHETIC'},headers:{'idempotency-key':randomUUID()}})).status(),403);
  await page.goto(f.origin+'/ops/');
  await page.getByRole('textbox',{name:'管理员账号',exact:true}).fill(f.username);
  await page.getByLabel('密码',{exact:true}).fill(f.password);
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await page.getByRole('button',{name:'赠送会籍',exact:true}).click();
  await page.getByLabel('手机号',{exact:true}).fill('13800000000');
  await page.getByRole('button',{name:'查找账号',exact:true}).click();
  await expect(page.getByText('身份依据已核验',{exact:true})).toBeVisible();
  await page.getByLabel('我已核对该账号与获批受赠对象一致').check();
  await page.getByLabel('赠送等级',{exact:true}).selectOption('star');
  await page.getByLabel('赠送原因',{exact:true}).fill('SYNTHETIC full-chain verification');
  await page.getByLabel('批准依据',{exact:true}).fill('SYNTHETIC-APPROVAL');
  await page.getByRole('button',{name:'检查赠送条件',exact:true}).click();
  await page.getByLabel('确认本次赠送一年星级会员，不修改付款订单').check();
  // A committed server response is lost in transit. The real UI must recover
  // by its saved operation ID rather than creating a second grant.
  let lost=false,received;
  const delivered=new Promise(resolve=>received=resolve);
  await page.route('**/api/admin/membership-grants',async route=>{
    if(!lost&&route.request().method()==='POST'){lost=true;const response=await route.fetch();received({status:response.status(),body:await response.json()});return route.abort('failed');}
    return route.continue();
  });
  await page.getByRole('button',{name:'确认赠送',exact:true}).click();
  await expect(page.getByText('待核对的赠送操作',{exact:true})).toBeVisible();
  const delivery=await delivered;assert.equal(delivery.status,200,JSON.stringify(delivery.body));
  await expect(page.getByRole('alert').filter({hasText:'本次结果尚未确认'})).toBeVisible();
  const beforeRecovery=(await f.pg.query('SELECT id,starts_at FROM collab_grants')).rows;assert.equal(beforeRecovery.length,1);
  await page.reload();await page.getByRole('button',{name:'赠送会籍',exact:true}).click();
  await page.getByRole('button',{name:'核对原操作结果',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'赠送结果已确认'})).toBeVisible();
  assert.deepEqual((await f.pg.query('SELECT id,starts_at FROM collab_grants')).rows,beforeRecovery);
  const me=await(await native.get(f.origin+'/api/me')).json();
  assert.equal(me.membership,null);assert.equal(me.displayMembership.planId,'star');assert.equal(me.effectiveEntitlements.active,true);
  assert.equal((await f.pg.query('SELECT * FROM orders')).rows.length,0);
  assert.equal((await native.get(f.origin+'/api/exclusive-contacts')).status(),200);
  const full=await native.get(fullUrl);assert.equal(full.status(),200);assert.deepEqual(await full.body(),f.full);assert.equal((await PDFDocument.load(await full.body())).getPageCount(),12);
  const range=await native.get(fullUrl,{headers:{Range:'bytes=0-4'}});assert.equal(range.status(),206);assert.equal((await range.body()).toString(),'%PDF-');
  assert.equal((await other.get(fullUrl)).status(),404);
  const post=await native.post(f.origin+'/api/posts',{data:{title:'SYNTHETIC full chain post',body:'SYNTHETIC text, no customer data'},headers:{'idempotency-key':randomUUID()}});assert.equal(post.status(),201);
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  await page.getByLabel('撤销原因',{exact:true}).fill('SYNTHETIC revocation verification');
  await page.getByRole('button',{name:'确认撤销',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'撤销结果已确认'})).toBeVisible();
  assert.equal((await native.get(fullUrl)).status(),404);
  assert.equal((await native.get(fullUrl,{headers:{Range:'bytes=0-4'}})).status(),404);
  assert.equal((await native.get(f.origin+'/api/exclusive-contacts')).status(),403);
  const revoked=await(await native.get(f.origin+'/api/me')).json();assert.equal(revoked.displayMembership,null);assert.equal(revoked.membership,null);
  assert.equal((await native.post(f.origin+'/api/posts',{data:{title:'After',body:'SYNTHETIC'},headers:{'idempotency-key':randomUUID()}})).status(),403);
  assert.equal((await(await native.get(f.origin+'/api/posts')).json()).posts.length,1);
  const preview=await native.get(f.origin+'/api/articles/'+f.reportId+'/preview');assert.equal(preview.status(),200);assert.equal((await PDFDocument.load(await preview.body())).getPageCount(),10);
  await page.reload();await page.getByRole('button',{name:'赠送会籍',exact:true}).click();
  await page.getByLabel('查找方式',{exact:true}).selectOption('userId');await page.getByLabel('已注册用户编号',{exact:true}).fill(f.user.id);await page.getByRole('button',{name:'查找账号',exact:true}).click();
  await expect(page.getByRole('cell',{name:/星级会员.*已撤销/})).toBeVisible();
  assert.equal((await f.pg.query("SELECT * FROM collab_grants WHERE status='revoked'")).rows.length,1);
  await mkdir('work/grant-e2e',{recursive:true});await page.screenshot({path:'work/grant-e2e/revoked-history.png',fullPage:true});
  await page.getByRole('button',{name:'退出登录',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'管理员账号',exact:true})).toBeVisible();
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
});
