-- U52 baseline: SQLite schema versions 1-14. Apply only to a NEW isolated schema.
-- INTEGER -> BIGINT; dates/JSON remain TEXT with C collation; BLOB -> BYTEA.
-- Explicit historical IDs remain valid; sequences are restored by the importer.

CREATE TABLE schema_version (version BIGINT PRIMARY KEY);

CREATE TABLE users (
      id TEXT COLLATE "C" PRIMARY KEY, username TEXT COLLATE "C" NOT NULL UNIQUE, password_hash TEXT COLLATE "C" NOT NULL,
      role TEXT COLLATE "C" NOT NULL CHECK(role IN ('member','admin')), created_at TEXT COLLATE "C" NOT NULL,
      referral_code TEXT COLLATE "C" NOT NULL UNIQUE,
      referrer_id TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, referral_source TEXT COLLATE "C" CHECK(referral_source IN ('explicit','default')),
      referral_at TEXT COLLATE "C", referral_locked_at TEXT COLLATE "C", consent_version TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE sessions (
      token_hash TEXT COLLATE "C" PRIMARY KEY, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, expires_at TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE native_sessions (
      token_hash TEXT COLLATE "C" PRIMARY KEY, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
      expires_at TEXT COLLATE "C" NOT NULL, auth_mode TEXT COLLATE "C" NOT NULL CHECK(auth_mode IN ('local-trial','wechat'))
    );

CREATE TABLE wechat_identities (
      app_id TEXT COLLATE "C" NOT NULL, open_id TEXT COLLATE "C" NOT NULL, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
      created_at TEXT COLLATE "C" NOT NULL, PRIMARY KEY(app_id,open_id), UNIQUE(app_id,user_id)
    );

CREATE TABLE settings (key TEXT COLLATE "C" PRIMARY KEY, value TEXT COLLATE "C" NOT NULL);

CREATE TABLE orders (
      id TEXT COLLATE "C" PRIMARY KEY, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, plan_id TEXT COLLATE "C" NOT NULL,
      amount_cents BIGINT NOT NULL CHECK(amount_cents > 0), currency TEXT COLLATE "C" NOT NULL DEFAULT 'CNY',
      status TEXT COLLATE "C" NOT NULL CHECK(status IN ('review','pending','paid','cancelled','rejected')),
      profile_json TEXT COLLATE "C" NOT NULL, created_at TEXT COLLATE "C" NOT NULL, paid_at TEXT COLLATE "C", expires_at TEXT COLLATE "C",
      actual_paid_cents BIGINT, referrer_id TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, referral_source TEXT COLLATE "C",
      reviewed_by TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, reviewed_at TEXT COLLATE "C", review_note TEXT COLLATE "C",
      idempotency_key TEXT COLLATE "C" NOT NULL, request_hash TEXT COLLATE "C" NOT NULL,
      UNIQUE(user_id,idempotency_key)
    );

CREATE UNIQUE INDEX one_open_order ON orders(user_id) WHERE status IN ('review','pending');

CREATE TABLE memberships (
      user_id TEXT COLLATE "C" PRIMARY KEY REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, order_id TEXT COLLATE "C" NOT NULL UNIQUE REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
      plan_id TEXT COLLATE "C" NOT NULL, starts_at TEXT COLLATE "C" NOT NULL, expires_at TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE payment_receipts (
      transaction_id TEXT COLLATE "C" PRIMARY KEY, order_id TEXT COLLATE "C" NOT NULL REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
      payload_hash TEXT COLLATE "C" NOT NULL, received_at TEXT COLLATE "C" NOT NULL, outcome TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE posts (
      id TEXT COLLATE "C" PRIMARY KEY, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, title TEXT COLLATE "C" NOT NULL, body TEXT COLLATE "C" NOT NULL,
      status TEXT COLLATE "C" NOT NULL CHECK(status IN ('pending','published','rejected')), reason TEXT COLLATE "C",
      created_at TEXT COLLATE "C" NOT NULL, reviewed_by TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, reviewed_at TEXT COLLATE "C",
      idempotency_key TEXT COLLATE "C" NOT NULL, UNIQUE(user_id,idempotency_key)
    );

CREATE TABLE audit_log (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id TEXT COLLATE "C", action TEXT COLLATE "C" NOT NULL,
      target_id TEXT COLLATE "C" NOT NULL, detail TEXT COLLATE "C" NOT NULL, created_at TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE articles (
      id TEXT COLLATE "C" PRIMARY KEY, title TEXT COLLATE "C" NOT NULL, summary TEXT COLLATE "C" NOT NULL, body TEXT COLLATE "C" NOT NULL,
      category TEXT COLLATE "C" NOT NULL CHECK(category IN ('news','knowledge')),
      access_json TEXT COLLATE "C" NOT NULL, status TEXT COLLATE "C" NOT NULL CHECK(status IN ('draft','published')),
      revision BIGINT NOT NULL CHECK(revision > 0), created_by TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
      updated_by TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, created_at TEXT COLLATE "C" NOT NULL, updated_at TEXT COLLATE "C" NOT NULL,
      published_at TEXT COLLATE "C", idempotency_key TEXT COLLATE "C" NOT NULL, creation_hash TEXT COLLATE "C" NOT NULL,
      UNIQUE(created_by,idempotency_key)
    );

CREATE TABLE feedback_tickets (
      seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT COLLATE "C" NOT NULL UNIQUE, user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
      title TEXT COLLATE "C" NOT NULL, body TEXT COLLATE "C" NOT NULL, category TEXT COLLATE "C" NOT NULL,
      status TEXT COLLATE "C" NOT NULL CHECK(status IN ('open','processing','resolved')), revision BIGINT NOT NULL,
      created_at TEXT COLLATE "C" NOT NULL, updated_at TEXT COLLATE "C" NOT NULL, idempotency_key TEXT COLLATE "C" NOT NULL, request_hash TEXT COLLATE "C" NOT NULL, member_read_seq BIGINT NOT NULL DEFAULT 0, confirmed_at TEXT COLLATE "C", related_order_id TEXT COLLATE "C" REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
      UNIQUE(user_id,idempotency_key)
    );

CREATE TABLE feedback_events (
      seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id TEXT COLLATE "C" NOT NULL REFERENCES feedback_tickets(id) DEFERRABLE INITIALLY DEFERRED,
      actor_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, action TEXT COLLATE "C" NOT NULL CHECK(action IN ('accept','reply')),
      body TEXT COLLATE "C" NOT NULL, status TEXT COLLATE "C" NOT NULL, created_at TEXT COLLATE "C" NOT NULL,
      idempotency_key TEXT COLLATE "C" NOT NULL, request_hash TEXT COLLATE "C" NOT NULL, author_kind TEXT COLLATE "C" NOT NULL DEFAULT 'staff', UNIQUE(actor_id,idempotency_key)
    );

CREATE TABLE service_resources (
      id TEXT COLLATE "C" PRIMARY KEY, title TEXT COLLATE "C" NOT NULL, summary TEXT COLLATE "C" NOT NULL, body TEXT COLLATE "C" NOT NULL,
      category TEXT COLLATE "C" NOT NULL CHECK(category IN ('translation','lectures','directory','visits')),
      access_json TEXT COLLATE "C" NOT NULL, action_json TEXT COLLATE "C" NOT NULL, status TEXT COLLATE "C" NOT NULL CHECK(status IN ('draft','published')),
      revision BIGINT NOT NULL CHECK(revision > 0), created_by TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
      updated_by TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED, created_at TEXT COLLATE "C" NOT NULL, updated_at TEXT COLLATE "C" NOT NULL,
      published_at TEXT COLLATE "C", idempotency_key TEXT COLLATE "C" NOT NULL, creation_hash TEXT COLLATE "C" NOT NULL,
      UNIQUE(created_by,idempotency_key)
    );

CREATE TABLE article_documents (
    article_id TEXT COLLATE "C" PRIMARY KEY REFERENCES articles(id) DEFERRABLE INITIALLY DEFERRED, sha256 TEXT COLLATE "C" NOT NULL UNIQUE,
    filename TEXT COLLATE "C" NOT NULL, byte_size BIGINT NOT NULL CHECK(byte_size>0),
    pages BIGINT NOT NULL CHECK(pages>0), imported_at TEXT COLLATE "C" NOT NULL
  );

CREATE TABLE report_previews (
    article_id TEXT COLLATE "C" PRIMARY KEY REFERENCES article_documents(article_id) DEFERRABLE INITIALLY DEFERRED,
    sha256 TEXT COLLATE "C" NOT NULL UNIQUE, byte_size BIGINT NOT NULL CHECK(byte_size>0),
    pages BIGINT NOT NULL CHECK(pages BETWEEN 1 AND 10)
  );

CREATE TABLE activities (
    id TEXT COLLATE "C" PRIMARY KEY, content_json TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL CHECK(status IN ('draft','published')), revision BIGINT NOT NULL CHECK(revision>0),
    created_by TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,created_at TEXT COLLATE "C" NOT NULL,updated_at TEXT COLLATE "C" NOT NULL,
    published_at TEXT COLLATE "C",idempotency_key TEXT COLLATE "C" NOT NULL,creation_hash TEXT COLLATE "C" NOT NULL,UNIQUE(created_by,idempotency_key)
  );

CREATE TABLE survey_submissions (
      seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT COLLATE "C" NOT NULL UNIQUE,
      survey_id TEXT COLLATE "C" NOT NULL, version TEXT COLLATE "C" NOT NULL, answers_json TEXT COLLATE "C" NOT NULL,
      submitted_at TEXT COLLATE "C" NOT NULL, idempotency_key TEXT COLLATE "C" NOT NULL UNIQUE, request_hash TEXT COLLATE "C" NOT NULL
    );

CREATE TABLE ambassador_applications (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT COLLATE "C" NOT NULL UNIQUE, user_id TEXT COLLATE "C" NOT NULL UNIQUE REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    contact TEXT COLLATE "C" NOT NULL, introduction TEXT COLLATE "C" NOT NULL, status TEXT COLLATE "C" NOT NULL CHECK(status IN ('pending','contacted')),
    staff_note TEXT COLLATE "C" NOT NULL DEFAULT '', created_at TEXT COLLATE "C" NOT NULL, updated_at TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1, idempotency_key TEXT COLLATE "C" NOT NULL, request_hash TEXT COLLATE "C" NOT NULL
  );

CREATE TABLE manual_payments (
    order_id TEXT COLLATE "C" PRIMARY KEY REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED, payer TEXT COLLATE "C" NOT NULL, payer_reference TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL CHECK(status IN ('pending','rejected','confirmed')), revision BIGINT NOT NULL,
    submitted_at TEXT COLLATE "C" NOT NULL, note TEXT COLLATE "C" NOT NULL DEFAULT '', reviewed_by TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    reviewed_at TEXT COLLATE "C", transaction_id TEXT COLLATE "C" UNIQUE, amount_cents BIGINT, paid_at TEXT COLLATE "C"
  );

CREATE TABLE legal_consents (
    id TEXT COLLATE "C" PRIMARY KEY,user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    scope TEXT COLLATE "C" NOT NULL CHECK(scope IN ('registration','order','payment')),
    target_id TEXT COLLATE "C" NOT NULL,release_id TEXT COLLATE "C" NOT NULL,documents_json TEXT COLLATE "C" NOT NULL,
    accepted_at TEXT COLLATE "C" NOT NULL,hong_kong_accepted BIGINT NOT NULL DEFAULT 0,details_confirmed BIGINT NOT NULL DEFAULT 0,UNIQUE(user_id,scope,target_id,release_id)
  );

CREATE TABLE enterprise_intakes (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id TEXT COLLATE "C" NOT NULL UNIQUE,
  company TEXT COLLATE "C" NOT NULL,contact TEXT COLLATE "C" NOT NULL,phone TEXT COLLATE "C" NOT NULL,note TEXT COLLATE "C" NOT NULL,
  answers_json TEXT COLLATE "C" NOT NULL,fields_json TEXT COLLATE "C" NOT NULL,
  filename TEXT COLLATE "C" NOT NULL,byte_size BIGINT NOT NULL,sha256 TEXT COLLATE "C" NOT NULL,file_data BYTEA NOT NULL,
  submitted_at TEXT COLLATE "C" NOT NULL,template_version TEXT COLLATE "C" NOT NULL,consent_json TEXT COLLATE "C" NOT NULL,
  idempotency_key TEXT COLLATE "C" NOT NULL UNIQUE,request_hash TEXT COLLATE "C" NOT NULL
 );

CREATE TABLE web_oauth_states (state_hash TEXT COLLATE "C" PRIMARY KEY,browser_hash TEXT COLLATE "C" NOT NULL,expires_at BIGINT NOT NULL,user_id TEXT COLLATE "C" REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,payload TEXT COLLATE "C" NOT NULL);
