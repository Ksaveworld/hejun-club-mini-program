import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const source = new URL('../miniprogram/data/service-directory.json', import.meta.url);
const target = new URL('../miniprogram/data/service-directory.js', import.meta.url);
export function nativeDirectorySource() {
  const data = JSON.parse(readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));
  if (!Array.isArray(data) || data.length !== 6 || data.some(c => !c.id || !Array.isArray(c.modules)))
    throw new Error('服务名录规范数据结构变化，请核对六类服务及模块');
  return '// Generated by scripts/sync-native-data.mjs. Edit service-directory.json instead.\n'
    + 'module.exports = ' + JSON.stringify(data, null, 2) + ';\n';
}
export function checkNativeDirectory() {
  try {return readFileSync(target, 'utf8') === nativeDirectorySource();} catch {return false;}
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (!checkNativeDirectory()) throw new Error('原生名录副本未同步，请运行 npm run native:data');
    console.log('原生名录副本与网页共享JSON一致');
  } else {
    writeFileSync(target, nativeDirectorySource(), 'utf8');
    console.log('已从共享JSON生成原生名录模块');
  }
}
